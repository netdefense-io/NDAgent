const capturedManagedRule = "221f3268-097c-440a-8a8f-adbd0d7d3bf9"

// searchRow returns the captured search row with this uuid.
func searchRow(t *testing.T, uuid string) map[string]interface{} {
	t.Helper()
	for _, r := range searchRows26(t) {
		if r["uuid"] == uuid {
			return r
		}
	}
	t.Fatalf("no captured row %s", uuid)
	return nil
}

